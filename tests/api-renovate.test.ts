function body(rows: Array<[string, string, string]>, automerge: boolean) {
  return [
    "This PR contains the following updates:",
    "",
    "| Package | Update | Change |",
    "|---|---|---|",
    ...rows.map(
      ([name, update, change]) =>
        `| [${name}](https://redirect.github.com/example) | ${update} | ${change} |`,
    ),
    "",
    "---",
    "",
    `🚦 **Automerge**: ${automerge ? "Enabled" : "Disabled by config. Please merge this manually once you are satisfied."}`,
    "",
    "This PR was generated by [Mend Renovate](https://mend.io/renovate/).",
  ].join("\n");
}

function pull(
  number: number,
  options: {
    title: string;
    branch: string;
    author?: string;
    sha: string;
    body: string;
    draft?: boolean;
  },
) {
  return {
    number,
    title: options.title,
    html_url: `https://github.com/${repository}/pull/${number}`,
    state: "open",
    draft: options.draft ?? false,
    user: { login: options.author ?? "renovate[bot]" },
    head: { ref: options.branch, sha: options.sha },
    base: { ref: "main", sha: "b".repeat(40) },
    body: options.body,
  };
}

function changed(
  filename: string,
  from: string,
  to: string,
  patch: string,
) {
  return {
    filename,
    status: "modified",
    additions: 1,
    deletions: 1,
    patch,
  };
}

